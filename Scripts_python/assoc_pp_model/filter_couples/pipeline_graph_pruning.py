# ----------------------- Utilities -----------------------

def benjamini_hochberg(pvals):
    """Benjamini–Hochberg FDR correction. Keeps shape & order."""
    p = np.asarray(pvals, dtype=float)
    n = len(p)
    order = np.argsort(p)
    q = np.empty_like(p)
    prev = 1.0
    for r, idx in enumerate(order[::-1], start=1):
        qq = min(prev, p[idx] * n / r)
        q[idx] = qq
        prev = qq
    return q

def exact_sign_test_greater(diff):
    """Exact one-sided sign test for H1: median(diff) > 0. Ties (0) removed."""
    y = np.asarray(diff)
    y = y[np.abs(y) > 0]
    n = len(y)
    if n == 0:
        return None
    s = int(np.sum(y > 0))
    res = binomtest(s, n, 0.5, alternative="greater")
    return float(res.pvalue) if hasattr(res, "pvalue") else float(res)

def spearman_hybrid_pvalue(x, y, n_perm=10000, seed=42):
    """Hybrid one-sided Spearman test (H1: rho > 0).
       If n < 30 -> permutation p-value; else -> asymptotic one-sided p-value.
       Returns (rho, p_one_sided, n_used).
    """
    mask = np.isfinite(x) & np.isfinite(y)
    x, y = x[mask], y[mask]
    n = len(x)
    if n < 3:
        return np.nan, np.nan, n
    rho, p_two = spearmanr(x, y)
    if np.isnan(rho):
        return np.nan, np.nan, n
    if n < 30:
        rng = np.random.default_rng(seed)
        cnt = 0
        for _ in range(n_perm):
            yp = rng.permutation(y)
            rp, _ = spearmanr(x, yp)
            if np.isfinite(rp) and rp >= rho:
                cnt += 1
        p_one = (cnt + 1) / (n_perm + 1)
    else:
        p_one = p_two / 2 if rho > 0 else 1 - p_two / 2
    return float(rho), float(p_one), n


