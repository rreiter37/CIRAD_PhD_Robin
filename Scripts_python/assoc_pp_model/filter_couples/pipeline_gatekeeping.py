def discover_dataset_csvs(root="Results/assoc_pp_model"):
    dataset_files = []
    for ds in sorted(os.listdir(root)):
        ds_dir = os.path.join(root, ds)
        if not os.path.isdir(ds_dir):
            continue
        candidates = [f for f in os.listdir(ds_dir)
                      if f.startswith("results_") and f.endswith(".csv")
                      and not any(bad in f for bad in ["CNN","LGBM","PLS","Ridge","NICON","dynamic"])]
        if candidates:
            candidates.sort()
            dataset_files.append((ds, os.path.join(ds_dir, candidates[0])))
    return dataset_files


def collect_and_merge_results(dataset_csvs):
    """
    Load all dataset CSVs and merge them into a unified DataFrame.
    CNN and NICON are considered the same model family and are merged by averaging their metrics.
    """
    all_dfs = []

    for ds, path in dataset_csvs:
        try:
            df = pd.read_csv(path)
        except Exception:
            continue

        # --- Skip invalid CSVs ---
        if "Model" not in df.columns:
            continue

        # --- Detect task type ---
        models = df["Model"].astype(str)
        if any(m.endswith("_reg") for m in models):
            task = "regression"
        elif any(m.endswith("_classif") for m in models):
            task = "classification"
        else:
            continue

        # --- Long-format melt ---
        long = df.melt(id_vars=["Model"], var_name="prep", value_name="metric")
        long["dataset"] = ds
        long["task"] = task
        long.rename(columns={"Model": "candidate_model"}, inplace=True)

        # --- 🔹 Merge CNN and NICON together ---
        # Step 1: Normalize model names — treat all CNN* as NICON*
        long["candidate_model"] = long["candidate_model"].replace(
            {m: m.replace("CNN", "NICON") for m in long["candidate_model"] if "CNN" in m}
        )

        # Step 2: Aggregate duplicates (same model, prep, dataset)
        long = (
            long.groupby(["candidate_model", "prep", "dataset", "task"], as_index=False)
                .agg({"metric": "mean"})
        )

        all_dfs.append(long)

    # --- Final concatenation ---
    if not all_dfs:
        return pd.DataFrame()
    return pd.concat(all_dfs, ignore_index=True)

def build_selection_table(df_task: pd.DataFrame,
                          kept_mask: pd.Series) -> pd.DataFrame:
    """
    Build a flat selection table with mean/std metric per (model, preprocessing)
    and a 'selected' flag from kept_mask.
    """
    # Mean / std across datasets for each (model, prep)
    stats = (
        df_task
        .groupby(["candidate_model", "prep"], as_index=True)["metric"]
        .agg(metric_mean="mean", metric_std="std")
    )

    # Align kept_mask (MultiIndex) into a DataFrame
    sel = kept_mask.rename("selected").to_frame()

    # Join and tidy
    out = stats.join(sel, how="left")
    out["selected"] = out["selected"].fillna(False).astype(bool)

    # Final column names as requested
    out = out.reset_index().rename(columns={
        "candidate_model": "model_name",
        "prep": "preprocessing_name"
    })
    # Optional dataset column (left empty to indicate “aggregated across datasets”)
    out["dataset_name"] = ""  # keep the column for downstream pivots

    # Reorder columns
    out = out[["model_name", "preprocessing_name", "dataset_name", "metric_mean", "metric_std", "selected"]]
    return out

