def iterative_gatekeeping(df: pd.DataFrame, delta: float, alpha: float,
                          n_perm: int, seed: int, batch_size: int):
    """
    Adaptive gatekeeping selection:
      Gate 1: performance degradation vs dataset-wise best model
      Gate 2: redundancy via maxT permutation correlation
    """
    mat = df.pivot_table(index=["candidate_model", "prep"], columns="dataset", values="metric", aggfunc="mean")
    kept_mask = pd.Series(False, index=mat.index)
    records = {}

    # Compute dataset-wise best performances
    task_type = df["task"].iloc[0]
    best_per_dataset = (df.groupby("dataset")["metric"].min()
                        if task_type == "regression"
                        else df.groupby("dataset")["metric"].max())

    for idx in tqdm(mat.index, desc="Gatekeeping iteration"):
        vec = mat.loc[idx].dropna()
        if len(vec) < 3:
            records[idx] = {"gate1_p": None, "gate2_p": None, "decision": "SKIP"}
            continue

        # --- Gate 1: performance degradation test (vs best model per dataset) ---
        diffs = []
        for ds, val in vec.items():
            if ds in best_per_dataset.index:
                diffs.append(val - best_per_dataset.loc[ds])
        diffs = np.array(diffs)

        if len(diffs) == 0:
            p1 = None
            median_gain = np.nan
        else:
            p1 = exact_sign_test(diffs, delta)
            median_gain = np.median(diffs)  # <-- NEW: median gain vs best

        # --- Gate 2: redundancy correlation test ---
        if kept_mask.any():
            kept_block = mat.loc[kept_mask]
            T_obs, p2, m_valid = gate2_maxT_permutation_vectorized(
                vec, kept_block,
                rng_seed=seed,
                n_perm=n_perm,
                batch_size=batch_size
            )
        else:
            T_obs, p2, m_valid = np.nan, np.nan, 0

        # Record everything
        records[idx] = {
            "gate1_p": p1,
            "gate2_p": p2,
            "rho_max": T_obs,
            "m_valid": m_valid,
            "median_gain_vs_best": median_gain  # <-- NEW field stored for plotting
        }

        # Decision to whether exclude a couple or keep it
        condition_perf = (p1 is not None and p1 < alpha)
        condition_corr = (p2 is not None and p2 < alpha) and (T_obs > args.corr_threshold)
        if condition_perf and condition_corr:
            kept_mask.loc[idx] = False
            records[idx]["decision"] = "EXCLUDE"
        else:
            kept_mask.loc[idx] = True
            records[idx]["decision"] = "KEEP"

    # Build the report DataFrame safely
    report_df = pd.DataFrame.from_dict(records, orient="index")
    if isinstance(report_df.index, pd.MultiIndex):
        report_df = report_df.reset_index(names=["candidate_model", "prep"])
    else:
        report_df = report_df.reset_index()
        if "index" in report_df.columns:
            report_df[["candidate_model", "prep"]] = pd.DataFrame(
                report_df["index"].tolist(), index=report_df.index)
            report_df.drop(columns="index", inplace=True)

    # --- Apply BH correction to Gate 2 ---
    valid_p2 = report_df["gate2_p"].dropna()
    if len(valid_p2) > 0:
        q2 = benjamini_hochberg(valid_p2.values)
        report_df.loc[report_df["gate2_p"].notna(), "gate2_q"] = q2
    else:
        report_df["gate2_q"] = np.nan

    # --- Flag significant correlation (statistical + practical) ---
    report_df["corr_significant"] = (
        (report_df["gate2_q"] < alpha) &
        (report_df["rho_max"].abs() >= args.corr_threshold)
    )

    return report_df, kept_mask

