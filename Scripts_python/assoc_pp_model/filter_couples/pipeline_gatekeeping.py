def discover_dataset_csvs(root_dir: str) -> List[Tuple[str, str]]:
    """Discover per-dataset results CSVs: first 'results_*.csv' per dataset, excluding substrings."""
    pairs = []
    if not os.path.isdir(root_dir):
        print(f"[WARN] Root directory not found: {root_dir}")
        return pairs
    for ds in sorted(os.listdir(root_dir)):
        ds_dir = os.path.join(root_dir, ds)
        if not os.path.isdir(ds_dir): continue
        cands = [f for f in os.listdir(ds_dir)
                 if f.startswith(FILENAME_PREFIX) and f.lower().endswith(".csv")]
        cands = [f for f in cands if not any(excl in f for excl in FILENAME_EXCLUDE_SUBSTRINGS)]
        if not cands: continue
        cands.sort()
        pairs.append((ds, os.path.join(ds_dir, cands[0])))
    return pairs

def detect_task_from_models(models: List[str]) -> str:
    """Return 'regression', 'classification', 'ambiguous', or 'unknown' using suffixes _reg / _classif."""
    has_reg = any(isinstance(m, str) and m.endswith("_reg") for m in models)
    has_clf = any(isinstance(m, str) and m.endswith("_classif") for m in models)
    if has_reg and not has_clf: return "regression"
    if has_clf and not has_reg: return "classification"
    if has_reg and has_clf: return "ambiguous"
    return "unknown"

def collect_delta_profiles_by_task(root: str) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Read per-dataset CSVs, compute Δ per (model, prep, dataset), split by task.
    Δ definitions:
      - regression:    Δ = RRMSE(candidate) - min_model RRMSE (same dataset & prep)
      - classification:Δ = max_model Acc   - Acc(candidate)  (same dataset & prep)
    Returns two tidy DataFrames:
      diffs_reg: [dataset, candidate_model, prep, delta]
      diffs_clf: [dataset, candidate_model, prep, delta]
    """
    reg_rows, clf_rows = [], []
    pairs = discover_dataset_csvs(root)
    for ds, path in pairs:
        try:
            df = pd.read_csv(path)
        except Exception as e:
            print(f"[WARN] Failed to read {path}: {e}")
            continue
        if MODEL_COL not in df.columns:
            print(f"[WARN] Missing '{MODEL_COL}' in {path}, skip.")
            continue

        models = [str(x) for x in df[MODEL_COL].dropna().tolist()]
        task = detect_task_from_models(models)
        if task in ("ambiguous", "unknown"):
            print(f"[WARN] Dataset '{ds}' task={task}, skip.")
            continue

        tidy = df.melt(id_vars=[MODEL_COL], var_name="prep", value_name="metric").rename(columns={MODEL_COL:"model"})
        if EXCLUDE_PREPS:
            tidy = tidy[~tidy["prep"].isin(EXCLUDE_PREPS)]
        tidy["metric"] = pd.to_numeric(tidy["metric"], errors="coerce")
        tidy = tidy.dropna(subset=["metric"])
        if tidy.empty:
            continue

        pivot = tidy.pivot_table(index="model", columns="prep", values="metric", aggfunc="mean")
        for prep in pivot.columns:
            col = pivot[prep].dropna()
            if col.empty: continue
            if task == "regression":
                best = float(col.min())
                for cand in col.index:
                    dlt = float(col.loc[cand] - best)
                    reg_rows.append((ds, cand, str(prep), dlt))
            else:
                best = float(col.max())
                for cand in col.index:
                    dlt = float(best - col.loc[cand])
                    clf_rows.append((ds, cand, str(prep), dlt))
    diffs_reg = pd.DataFrame(reg_rows, columns=["dataset","candidate_model","prep","delta"])
    diffs_clf = pd.DataFrame(clf_rows, columns=["dataset","candidate_model","prep","delta"])
    return diffs_reg, diffs_clf

# ----------------------- Statistics: tests -----------------------

def exact_sign_test_inferiority(deltas: np.ndarray, delta_margin: float) -> Tuple[Optional[float], int]:
    """
    Exact one-sided Sign test for inferiority on Y = Δ - δ:
      H0: median(Y) <= 0  vs  H1: median(Y) > 0
    Ties (Y == 0) are removed. Returns (p_value, n_effective).
    """
    y = deltas - delta_margin
    eff = y[np.abs(y) > 0]
    n_eff = int(eff.size)
    if n_eff == 0:
        return None, 0
    s_pos = int(np.sum(eff > 0))
    if SCIPY_AVAILABLE:
        p = 1.0 - binom.cdf(s_pos - 1, n_eff, 0.5)
    else:
        # manual exact binomial upper tail
        from math import comb
        p = sum(comb(n_eff, k) * (0.5 ** n_eff) for k in range(s_pos, n_eff + 1))
    return float(p), n_eff

def wilcoxon_inferiority(deltas: np.ndarray, delta_margin: float) -> Tuple[Optional[float], int]:
    """
    One-sided Wilcoxon signed-rank on Y=Δ-δ with alternative='greater' (inferiority).
    Returns (p_value, n_eff non-zero). Provided for reporting only.
    """
    if not SCIPY_AVAILABLE:
        return None, 0
    y = deltas - delta_margin
    y = y[np.abs(y) > 0]
    n = len(y)
    if n == 0: return None, 0
    try:
        stat, p = wilcoxon(y, alternative="greater", zero_method="wilcox", correction=False, mode="auto")
        return float(p), n if isinstance(p, float) else (None, n)
    except Exception:
        return None, n

def spearman_perm_or_classical(x: np.ndarray, y: np.ndarray, n_perm: int = 10000, seed: int = 42) -> Tuple[float, float]:
    """
    Adaptive one-sided Spearman correlation test (H1: rho > 0).
      * If n < 30: permutation test (Monte Carlo, robust for small samples)
      * Else: classical Spearman test (approximate, one-sided)
    Handles constant inputs by returning rho=0, p=1.
    """
    rng = np.random.default_rng(seed)
    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]; y = y[mask]
    n = len(x)
    if n < 3:
        return 0.0, 1.0

    # Constant arrays -> undefined correlation
    if np.all(x == x[0]) or np.all(y == y[0]):
        return 0.0, 1.0

    # Compute observed Spearman
    try:
        rho_obs, _ = spearmanr(x, y)
    except Exception:
        rho_obs = np.nan
    if np.isnan(rho_obs):
        return 0.0, 1.0

    # Small sample -> permutation (one-sided right tail)
    if n < 30:
        rx = pd.Series(x).rank().to_numpy()
        ry = pd.Series(y).rank().to_numpy()
        rx_c = rx - rx.mean()
        ry_c = ry - ry.mean()
        denom = np.sqrt(np.dot(rx_c, rx_c) * np.dot(ry_c, ry_c))
        if denom == 0:
            return 0.0, 1.0
        rho_obs = float(np.dot(rx_c, ry_c) / denom)

        ge = 1  # add-one smoothing
        for _ in range(n_perm):
            rng.shuffle(ry)
            ry_c2 = ry - ry.mean()
            denom2 = np.sqrt(np.dot(rx_c, rx_c) * np.dot(ry_c2, ry_c2))
            if denom2 == 0:
                continue
            rho_perm = np.dot(rx_c, ry_c2) / denom2
            if rho_perm >= rho_obs - 1e-15:
                ge += 1
        p = ge / (n_perm + 1.0)
        return float(rho_obs), float(p)

    # Larger sample -> classical Spearman, one-sided right tail
    try:
        rho_obs, p_two = spearmanr(x, y)
        if np.isnan(rho_obs): return 0.0, 1.0
        p_one = p_two / 2 if rho_obs > 0 else 1 - p_two / 2
        p = max(min(p_one, 1.0), 0.0)
        return float(rho_obs), float(p)
    except Exception:
        return 0.0, 1.0

def benjamini_hochberg(pvals: List[Optional[float]]) -> List[Optional[float]]:
    """Benjamini–Hochberg FDR on a list of p-values (None/NaN preserved)."""
    idx = [(i, p) for i, p in enumerate(pvals) if p is not None and np.isfinite(p)]
    m = len(idx)
    q = [None] * len(pvals)
    if m == 0: return q
    idx.sort(key=lambda t: t[1])
    raw = [min(1.0, idx[k][1] * m / (k + 1)) for k in range(m)]
    for k in range(m - 2, -1, -1):
        raw[k] = min(raw[k], raw[k + 1])
    for k, (i, _) in enumerate(idx):
        q[i] = raw[k]
    return q

# ----------------------- Gatekeeping engine -----------------------

def envelope_profile(kept_block: pd.DataFrame, datasets: List[str]) -> np.ndarray:
    """Envelope v_S(d) = min_{row in kept_block} Δ(row, d)."""
    if kept_block.empty:
        return np.full(len(datasets), np.nan)
    return np.nanmin(kept_block[datasets].to_numpy(float), axis=0)

def iterative_gatekeeping(diffs: pd.DataFrame,
                          alpha: float,
                          delta: float,
                          n_perm: int,
                          seed: int,
                          max_epochs: int = 10):
    """
    Run iterative gatekeeping until convergence:
      1) Build candidate-by-dataset Δ matrix, order by median Δ (best first).
      2) Initialize S with the top-1 (always kept).
      3) Epoch loop:
           - Gate 1 for all not-in-S (inferiority test on Δ-δ).
           - Envelope v_S from current S.
           - Gate 2 for Gate-1-significant: Spearman (perm if n<30 else classical), BH–FDR within epoch.
           - EXCLUDE only if Gate1 sig AND Gate2 q<alpha; otherwise KEEP.
      4) Stop when S stabilizes or max_epochs reached.

    Returns:
      summary_df: per (model, prep) with p-values/q-values/decision
      kept_df: final kept (model, prep)
    """
    if diffs.empty:
        return pd.DataFrame(), pd.DataFrame(columns=["candidate_model","prep"])

    # Build Δ matrix
    mat = diffs.pivot_table(index=["candidate_model","prep"], columns="dataset", values="delta", aggfunc="mean")
    mat = mat.sort_index()
    datasets = list(mat.columns)
    med = mat.median(axis=1, skipna=True)
    order = med.sort_values().index
    mat = mat.loc[order]; med = med.loc[order]

    # Initialize S with top-1
    kept_mask = pd.Series(False, index=mat.index)
    if len(kept_mask) > 0: kept_mask.iloc[0] = True

    # Bookkeeping for reporting
    records: Dict[Tuple[str,str], Dict] = {idx: {"median_delta": float(med.loc[idx])} for idx in mat.index}

    prev_kept = None
    for epoch in range(1, max_epochs+1):
        gate2_candidates = []

        # Gate 1: performance (inferiority). Not-proven-worse -> KEEP immediately.
        for idx in mat.index:
            if kept_mask.loc[idx]: continue
            deltas = mat.loc[idx].to_numpy(float)
            deltas = deltas[np.isfinite(deltas)]
            p1, n1 = exact_sign_test_inferiority(deltas, delta)
            p1w, n1w = wilcoxon_inferiority(deltas, delta)
            rec = records[idx]
            rec.update({"gate1_perf_sign_p":p1, "gate1_perf_n_eff":n1,
                        "gate1_wilcoxon_p":p1w, "gate1_wilcoxon_n_eff":n1w})
            if p1 is None or p1 >= alpha:
                kept_mask.loc[idx] = True
                rec["gate1_pass"] = False
            else:
                rec["gate1_pass"] = True
                gate2_candidates.append(idx)

        # Envelope from current S
        kept_block = mat.loc[kept_mask]
        vS = envelope_profile(kept_block, datasets)

        # Gate 2: correlation vs envelope for Gate-1-significant only
        p_list, idx_list = [], []
        for idx in gate2_candidates:
            vec = mat.loc[idx].to_numpy(float)
            rho, p2 = spearman_perm_or_classical(vec, vS, n_perm=n_perm, seed=seed+epoch)
            records[idx]["gate2_corr_rho"] = rho
            records[idx]["gate2_corr_p"] = p2
            p_list.append(p2); idx_list.append(idx)

        # BH–FDR within epoch
        qvals = benjamini_hochberg(p_list) if p_list else []
        for idx, q2 in zip(idx_list, qvals):
            records[idx]["gate2_corr_q"] = q2

        # Decisions: exclude only if Gate1 sig AND Gate2 q<alpha; else keep.
        for idx in gate2_candidates:
            q2 = records[idx].get("gate2_corr_q", None)
            if q2 is not None and np.isfinite(q2) and q2 < alpha:
                kept_mask.loc[idx] = False; records[idx]["decision"] = "EXCLUDE"
            else:
                kept_mask.loc[idx] = True;  records[idx]["decision"] = "KEEP"

        kept_now = tuple(kept_mask[kept_mask].index)
        if prev_kept is not None and kept_now == prev_kept:
            break
        prev_kept = kept_now

    # Finalize summary
    rows = []
    for idx in mat.index:
        rec = records[idx]; model, prep = idx
        rows.append({
            "candidate_model": model, "prep": prep,
            "median_delta": rec.get("median_delta", np.nan),
            "gate1_perf_sign_p": rec.get("gate1_perf_sign_p", None),
            "gate1_perf_n_eff": rec.get("gate1_perf_n_eff", None),
            "gate1_wilcoxon_p": rec.get("gate1_wilcoxon_p", None),
            "gate1_wilcoxon_n_eff": rec.get("gate1_wilcoxon_n_eff", None),
            "gate2_corr_rho": rec.get("gate2_corr_rho", None),
            "gate2_corr_p": rec.get("gate2_corr_p", None),
            "gate2_corr_q": rec.get("gate2_corr_q", None),
            "decision": "KEEP" if kept_mask.loc[idx] else "EXCLUDE"
        })
    summary = pd.DataFrame(rows).sort_values(["decision","median_delta","candidate_model","prep"])
    kept_df = summary[summary["decision"]=="KEEP"][["candidate_model","prep"]].reset_index(drop=True)
    return summary, kept_df

