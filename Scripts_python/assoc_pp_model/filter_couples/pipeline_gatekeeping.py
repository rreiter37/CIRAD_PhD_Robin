def benjamini_hochberg(pvals):
    """Benjamini–Hochberg FDR correction."""
    pvals = np.array(pvals, dtype=float)
    n = len(pvals)
    order = np.argsort(pvals)
    qvals = np.empty_like(pvals)
    prev_q = 1.0
    for rank, idx in enumerate(order[::-1], start=1):
        q = min(prev_q, pvals[idx] * n / (n - rank + 1))
        qvals[idx] = q
        prev_q = q
    return qvals


def exact_sign_test(diff, delta):
    """Exact one-sided sign test: H0 median(diff - delta) <= 0 vs H1 > 0."""
    y = diff - delta
    y = y[np.abs(y) > 0]
    n = len(y)
    if n == 0:
        return None
    s = np.sum(y > 0)
    p_res = binomtest(s, n, 0.5, alternative="greater")
    return float(p_res.pvalue if hasattr(p_res, "pvalue") else p_res)

