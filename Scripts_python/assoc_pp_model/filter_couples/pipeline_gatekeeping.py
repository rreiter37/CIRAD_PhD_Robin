# Vectorized Westfall–Young maxT permutation test (fixed)
# ===============================================================

def gate2_maxT_permutation_vectorized(candidate_vec: pd.Series,
                                      kept_block: pd.DataFrame,
                                      rng_seed: int = 42,
                                      n_perm: int = 10000,
                                      use_resid: bool = True,
                                      batch_size: int = 256):
    """
    Vectorized Westfall–Young maxT permutation test for correlation redundancy (ρ > 0).
    Now skips constant/degenerate vectors and handles NaNs safely.
    """
    rng = np.random.default_rng(rng_seed)
    valid_pairs = []
    rho_obs = []

    # Gather valid correlation pairs
    for idx in kept_block.index:
        y = kept_block.loc[idx].dropna()
        common = candidate_vec.index.intersection(y.index)
        if len(common) < 3:
            continue
        x_vals = candidate_vec.loc[common].to_numpy(dtype=float)
        y_vals = y.loc[common].to_numpy(dtype=float)

        # Skip degenerate or constant vectors
        if np.nanstd(x_vals) < 1e-10 or np.nanstd(y_vals) < 1e-10:
            continue

        rho = spearmanr(x_vals, y_vals)[0]
        if np.isnan(rho) or np.isinf(rho):
            continue

        valid_pairs.append((x_vals, y_vals))
        rho_obs.append(rho)

    m_valid = len(valid_pairs)
    if m_valid == 0:
        return None, None, 0

    T_obs = float(np.nanmax(rho_obs))

    # Prepare rank-transformed matrices
    max_len = max(len(x) for (x, _) in valid_pairs)
    Xr = np.full((m_valid, max_len), np.nan)
    Yr = np.full((m_valid, max_len), np.nan)

    for i, (x, y) in enumerate(valid_pairs):
        rx = pd.Series(x).rank(method="average").to_numpy()
        ry = pd.Series(y).rank(method="average").to_numpy()
        if use_resid:
            rx -= rx.mean()
            ry -= ry.mean()
        Xr[i, :len(x)] = rx
        Yr[i, :len(y)] = ry

    denom_X = np.nansum(Xr**2, axis=1)**0.5
    denom_Y = np.nansum(Yr**2, axis=1)**0.5
    denom = denom_X * denom_Y
    valid_mask = denom > 0
    Xr, Yr, denom = Xr[valid_mask], Yr[valid_mask], denom[valid_mask]
    m_valid = Xr.shape[0]

    n = Xr.shape[1]
    perms = np.array([rng.permutation(n) for _ in range(n_perm)])
    max_stats = np.full(n_perm, -np.inf)

    for start in range(0, n_perm, batch_size):
        end = min(start + batch_size, n_perm)
        batch_perm = perms[start:end]
        X_perm = np.take_along_axis(np.broadcast_to(Xr, (end - start, *Xr.shape)),
                                    batch_perm[:, None, :], axis=2)
        cov = np.nansum(X_perm * Yr[None, :, :], axis=2)
        rhos = cov / denom[None, :]
        max_stats[start:end] = np.nanmax(rhos, axis=1)

    exceed = np.sum(max_stats >= T_obs - 1e-15)
    p_maxT = (exceed + 1.0) / (n_perm + 1.0)

    return float(T_obs), float(p_maxT), m_valid

