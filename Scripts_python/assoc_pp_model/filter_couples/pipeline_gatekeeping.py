"""
Iterative Gatekeeping Pipeline for (model, preprocessing) selection

Overview
--------
This monolithic script implements an adaptive, iterative gatekeeping strategy to keep
(model, preprocessing) pairs that are either:
  - not proven worse (performance-wise), or
  - worse but not redundantly correlated to the current kept set S.

We do NOT pre-specify how many pairs to keep; the final set emerges from data.

Gate 1 (Performance):
  - Build per-dataset Δ with a "best-per-prep" reference:
      * regression (smaller is better):    Δ = RRMSE(candidate) - min_model RRMSE (same dataset & prep)
      * classification (larger is better): Δ = max_model Acc   - Acc(candidate)   (same dataset & prep)
    Hence Δ >= 0 and larger means "worse".
  - One-sided nonparametric test on Y = Δ - δ:
      H0: median(Y) <= 0  vs  H1: median(Y) > 0  (inferiority)
    Use exact Sign test (robust); also report Wilcoxon (if SciPy available).
  - If NOT significant (p >= alpha): KEEP immediately.

Gate 2 (Correlation, only for Gate-1 significant items):
  - Compute envelope profile v_S(d) = min_{k in S} Δ_k(d) across datasets d.
  - Test Spearman correlation between candidate Δ_j and v_S:
      H0: rho = 0  vs  H1: rho > 0  (positive correlation means redundancy)
    * If number of datasets n < 30: permutation test (Monte Carlo, one-sided, robust for small n)
    * Else: classical Spearman test (unilateral right tail).
  - Apply Benjamini–Hochberg FDR to Gate-2 p-values within the epoch.
  - EXCLUDE only if (Gate 1 significant) AND (Gate 2 FDR-significant).

Iteration:
  - Initialize S with top-1 (lowest median Δ).
  - Iterate epochs (update S, envelope, tests) until convergence (no change in S) or max_epochs.

Outputs (per task: regression / classification)
-----------------------------------------------
- Results CSV: <prefix>_reg_report.csv / <prefix>_classif_report.csv
- Kept list:   <prefix>_reg_keep.csv   / <prefix>_classif_keep.csv
- Global figures in Figures/...:
    1) decision_heatmap.png
    2) pvalue_distributions.png
    3) scatter_perf_corr.png
    4) progression.png
    5) gate_map.png        (median Δ vs -log10 p1)
    6) corr_map.png        (rho vs q2)

Author: Generated by ChatGPT
All code comments are in English.
"""

