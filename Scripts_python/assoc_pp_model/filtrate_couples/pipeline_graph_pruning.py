"""
Adaptive diverse selection via graph pruning (with visualizations and Markdown report).

What this script does
---------------------
1) Builds per-(model, preprocessing) performance profiles across datasets (normalized RRMSE).
2) Tests pairwise profile correlation with a one-sided Spearman permutation test (H1: rho > 0).
   Applies BH-FDR across all tested pairs to identify significant positive-correlation edges.
3) Iterates candidates in order of increasing median normalized RRMSE (best-first).
   For each candidate j and the current kept set S:
     * Identify neighbors k in S significantly (FDR) positively correlated with j.
     * For those k, run an exact one-sided sign test on Δ = R_j - R_k with H1: median(Δ) > 0
       (candidate strictly worse). Apply BH-FDR within the comparisons of the same j.
     * If any k yields a significant result after FDR (i.e., j is worse than at least one correlated k),
       prune j; otherwise keep j.
4) Produces CSVs + figures:
   * decisions CSV (kept/pruned + reasons)
   * Spearman rho matrix CSV
   * FDR-adjusted p-values (correlation) CSV
   * Heatmap of significant positive correlations (PNG)
   * Network graph (PNG) with nodes colored by decision
   * Markdown report summarizing pruning relations with rho and q-values

Author: Generated by ChatGPT (comments in English).
"""

