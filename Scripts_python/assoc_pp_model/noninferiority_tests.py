def collect_diffs_across_datasets(dataset_csvs: List[Tuple[str, str]],
                                  reference_mode: str,
                                  reference_model: Optional[str]) -> pd.DataFrame:
    """For each dataset, build a tidy table and compute all usable Δ values
    for each (candidate_model, prep).

    Returns a DataFrame with columns:
      ['candidate_model', 'prep', 'dataset', 'delta_value'] where
      delta_value = RRMSE(candidate) - RRMSE(reference) for the specified reference_mode.
    """
    rows = []
    for ds_name, csv_path in dataset_csvs:
        try:
            df = pd.read_csv(csv_path)
        except Exception as e:
            print(f"[WARN] Failed to read {csv_path}: {e}")
            continue

        if MODEL_COL not in df.columns:
            print(f"[WARN] Missing '{MODEL_COL}' in {csv_path}, skipping.")
            continue

        # Melt into long format
        tidy = df.melt(id_vars=[MODEL_COL], var_name="prep", value_name="rrmse").rename(columns={MODEL_COL: "model"})
        tidy["rrmse"] = pd.to_numeric(tidy["rrmse"], errors="coerce")
        tidy = tidy.dropna(subset=["rrmse"])

        # Optional restrictions
        if RESTRICT_TO_PREPS is not None:
            if PREP_CASE_SENSITIVE:
                tidy = tidy[tidy["prep"].isin(RESTRICT_TO_PREPS)]
            else:
                lower_set = {p.lower() for p in RESTRICT_TO_PREPS}
                tidy = tidy[tidy["prep"].str.lower().isin(lower_set)]
        if RESTRICT_TO_MODELS is not None:
            tidy = tidy[tidy["model"].isin(RESTRICT_TO_MODELS)]

        # Pivot to model x prep for quick lookup
        pivot = tidy.pivot_table(index="model", columns="prep", values="rrmse", aggfunc="mean")

        # Candidate models are all models except the reference (if fixed)
        models = list(pivot.index)

        if reference_mode == "fixed_model":
            if reference_model is None:
                raise ValueError("REFERENCE_MODE == 'fixed_model' but REFERENCE_MODEL_NAME is None")
            if reference_model not in models:
                # No reference in this dataset, cannot compute diffs here
                continue
            ref_row = pivot.loc[reference_model]

            for cand in models:
                if cand == reference_model:
                    continue
                for prep in pivot.columns:
                    cand_val = pivot.loc[cand].get(prep, np.nan)
                    ref_val = ref_row.get(prep, np.nan)
                    if pd.notna(cand_val) and pd.notna(ref_val):
                        rows.append({
                            "candidate_model": cand,
                            "prep": prep,
                            "dataset": ds_name,
                            "delta_value": float(cand_val - ref_val)
                        })

        elif reference_mode == "per_dataset_best":
            # For each prep, find the model with the minimum RRMSE in this dataset
            for prep in pivot.columns:
                col = pivot[prep].dropna()
                if col.empty:
                    continue
                best_model = col.idxmin()
                best_val = col.loc[best_model]
                for cand in pivot.index:
                    # Skip if candidate is the best; comparing to itself gives zero and is not informative
                    if pd.isna(pivot.loc[cand, prep]) or cand == best_model:
                        continue
                    rows.append({
                        "candidate_model": cand,
                        "prep": prep,
                        "dataset": ds_name,
                        "delta_value": float(pivot.loc[cand, prep] - best_val)
                    })
        else:
            raise ValueError(f"Unknown reference_mode: {reference_mode}")

    return pd.DataFrame(rows)


def run_tests(diffs_df: pd.DataFrame,
              delta_margin: float,
              alpha: float,
              ci_level: float,
              bootstrap_B: int,
              seed: int) -> pd.DataFrame:
    """Run sign test, Wilcoxon, and bootstrap CI for each (candidate_model, prep) over datasets.
    Returns a tidy summary DataFrame.
    """
    results = []
    grouped = diffs_df.groupby(["candidate_model", "prep"], sort=False)
    for (cand, prep), g in grouped:
        diffs = g["delta_value"].to_numpy(dtype=float)
        # Remove NaNs
        diffs = diffs[np.isfinite(diffs)]
        if diffs.size == 0:
            continue

        # Exact sign test
        sign_p, sign_n = exact_sign_test_pvalue(diffs, delta_margin)

        # Wilcoxon (one-sided 'less')
        wil_p, wil_n = wilcoxon_less_pvalue(diffs, delta_margin)

        # Bootstrap CI for median(Δ)
        ci_lo, ci_hi = bootstrap_ci_median(diffs, ci=ci_level, B=bootstrap_B, seed=seed)

        # Point estimates
        median_diff = float(np.median(diffs))
        mean_diff = float(np.mean(diffs))

        # Decisions
        noninf_sign = (sign_p is not None) and (sign_p < alpha)
        noninf_wil = (wil_p is not None) and (wil_p < alpha)
        noninf_boot = (not math.isnan(ci_hi)) and (ci_hi < delta_margin)

        results.append({
            "candidate_model": cand,
            "prep": prep,
            "n_datasets": int(len(g["dataset"].unique())),
            "n_pairs": int(diffs.size),
            "median_diff": median_diff,
            "mean_diff": mean_diff,
            "sign_p": sign_p,
            "sign_n_eff": sign_n,
            "wilcoxon_p": wil_p,
            "wilcoxon_n_eff": wil_n,
            "boot_ci_low": ci_lo,
            "boot_ci_high": ci_hi,
            "noninferior_sign": noninf_sign,
            "noninferior_wilcoxon": noninf_wil,
            "noninferior_bootstrap": noninf_boot
        })

    out = pd.DataFrame(results)

    # FDR (BH) for p-values separately
    if not out.empty:
        out["sign_q"] = benjamini_hochberg(out["sign_p"].tolist())
        out["wilcoxon_q"] = benjamini_hochberg(out["wilcoxon_p"].tolist())

        # Add FDR-based decisions
        out["noninferior_sign_fdr"] = out["sign_q"].apply(lambda q: (q is not None) and (q < alpha))
        out["noninferior_wilcoxon_fdr"] = out["wilcoxon_q"].apply(lambda q: (q is not None) and (q < alpha))

    return out.sort_values(["candidate_model", "prep"]).reset_index(drop=True)



import matplotlib.pyplot as plt
import seaborn as sns

def make_visualizations(summary: pd.DataFrame, delta_margin: float, alpha: float, output_prefix: str):
    """Generate volcano plot, forest plot, and heatmap for quick exclusion/retention decisions."""

    if summary.empty:
        print("[WARN] No summary to visualize.")
        return

    # 1) Volcano plot (Wilcoxon p-value vs median_diff)
    plt.figure(figsize=(8,6))
    x = summary["median_diff"]
    y = -np.log10(summary["wilcoxon_p"].fillna(1.0))
    colors = []
    for md, p in zip(summary["median_diff"], summary["wilcoxon_p"]):
        if p is None or np.isnan(p):
            colors.append("gray")
        elif (p < alpha) and (md < delta_margin):
            colors.append("green")  # keep
        elif (p < alpha) and (md >= delta_margin):
            colors.append("red")    # worse
        else:
            colors.append("orange") # ambiguous
    plt.scatter(x, y, c=colors, alpha=0.7)
    plt.axvline(delta_margin, color="black", linestyle="--", label=f"delta={delta_margin}")
    plt.xlabel("Median Δ (RRMSE candidate - reference)")
    plt.ylabel("-log10 p-value (Wilcoxon)")
    plt.title("Volcano plot for non-inferiority")
    plt.legend()
    plt.tight_layout()
    plt.savefig(f"{output_prefix}_volcano.png")
    plt.close()

    # 2) Forest plot (bootstrap CI of median Δ)
    fig, ax = plt.subplots(figsize=(8, max(6, 0.3*len(summary))))
    sorted_summary = summary.sort_values("median_diff")
    y_positions = range(len(sorted_summary))
    ax.errorbar(x=sorted_summary["median_diff"], y=y_positions,
                xerr=[sorted_summary["median_diff"]-sorted_summary["boot_ci_low"],
                      sorted_summary["boot_ci_high"]-sorted_summary["median_diff"]],
                fmt='o', ecolor="gray", capsize=3)
    ax.axvline(delta_margin, color="red", linestyle="--", label=f"delta={delta_margin}")
    ax.set_yticks(y_positions)
    labels = [f"{m}|{p}" for m,p in zip(sorted_summary["candidate_model"], sorted_summary["prep"])]
    ax.set_yticklabels(labels, fontsize=6)
    ax.set_xlabel("Median Δ with bootstrap CI")
    ax.set_title("Forest plot of bootstrap CIs")
    ax.legend()
    plt.tight_layout()
    plt.savefig(f"{output_prefix}_forest.png")
    plt.close()

    # 3) Heatmap of decisions (Wilcoxon)
    # Decision matrix: rows=model, cols=prep
    decision_matrix = summary.pivot(index="candidate_model", columns="prep",
                                    values="noninferior_wilcoxon")
    # Map True/False/None to numeric codes
    cmap = {True:1, False:0, None:np.nan}
    mat = decision_matrix.applymap(lambda v: cmap.get(v, np.nan))
    plt.figure(figsize=(12, max(6,0.4*len(mat))))
    sns.heatmap(mat, cmap=sns.color_palette(["red","green"]), cbar=False, linewidths=0.5, linecolor="gray")
    plt.title("Heatmap of non-inferiority (Wilcoxon)")
    plt.xlabel("Preprocessing")
    plt.ylabel("Model")
    plt.tight_layout()
    plt.savefig(f"{output_prefix}_heatmap.png")
    plt.close()



def main():
    import argparse
    parser = argparse.ArgumentParser(description="Non-inferiority tests on RRMSE tables (sign test, Wilcoxon, bootstrap CI).")
    parser.add_argument("--root", type=str, default=RESULTS_ROOT, help="Root directory containing dataset subfolders.")
    parser.add_argument("--reference_mode", type=str, choices=["fixed_model", "per_dataset_best"], default=REFERENCE_MODE,
                        help="Reference choice: fixed model or per-dataset best (same preprocessing).")
    parser.add_argument("--reference_model", type=str, default=REFERENCE_MODEL_NAME,
                        help="Reference model name when reference_mode=fixed_model.")
    parser.add_argument("--delta", type=float, default=DELTA_MARGIN, help="Non-inferiority margin δ (in RRMSE units).")
    parser.add_argument("--alpha", type=float, default=ALPHA, help="Significance level for tests (one-sided).")
    parser.add_argument("--bootstrap", type=int, default=BOOTSTRAP_B, help="Number of bootstrap resamples for median CI.")
    parser.add_argument("--ci", type=float, default=CI_LEVEL, help="Confidence level for bootstrap CI.")
    parser.add_argument("--restrict_models", type=str, default=None,
                        help="JSON array of model names to include (or None).")
    parser.add_argument("--restrict_preps", type=str, default=None,
                        help="JSON array of preprocessing names to include (or None).")
    parser.add_argument("--output", type=str, default=OUTPUT_CSV, help="Output CSV file path.")
    args = parser.parse_args()

    # Apply restrictions if provided
    global RESTRICT_TO_MODELS, RESTRICT_TO_PREPS
    if args.restrict_models:
        RESTRICT_TO_MODELS = set(json.loads(args.restrict_models))
    if args.restrict_preps:
        RESTRICT_TO_PREPS = set(json.loads(args.restrict_preps))

    # Discover CSVs
    dataset_csvs = discover_dataset_csvs(args.root)
    if not dataset_csvs:
        print(f"[WARN] No dataset CSVs discovered under {args.root}.")
        return

    # Collect Δ across datasets
    diffs_df = collect_diffs_across_datasets(dataset_csvs, args.reference_mode, args.reference_model)
    if diffs_df.empty:
        print("[WARN] No comparable pairs could be formed. Check reference mode and data availability.")
        return

    # Run tests
    summary = run_tests(diffs_df,
                        delta_margin=args.delta,
                        alpha=args.alpha,
                        ci_level=args.ci,
                        bootstrap_B=args.bootstrap,
                        seed=RANDOM_SEED)

    # Save results
    summary.to_csv(args.output, index=False)
    print(f"[INFO] Saved report to: {args.output}")
    # Also save the raw diffs for traceability
    diffs_df.to_csv(os.path.splitext(args.output)[0] + "_diffs.csv", index=False)

    # Visualizations
    output_prefix = os.path.splitext(args.output)[0]
    make_visualizations(summary, delta_margin=args.delta, alpha=args.alpha, output_prefix=output_prefix)
    print(f"[INFO] Saved visualizations to {output_prefix}_*.png")


if __name__ == "__main__":
    main()