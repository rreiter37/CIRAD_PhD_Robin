def discover_dataset_csvs(root: str) -> List[Tuple[str, str]]:
    """Discover (dataset_name, csv_path) pairs under root.
    We pick the FIRST CSV in each dataset dir that matches the rules.
    """
    pairs = []
    if not os.path.isdir(root):
        print(f"[WARN] Root directory not found: {root}")
        return pairs

    for ds in sorted(os.listdir(root)):
        ds_dir = os.path.join(root, ds)
        if not os.path.isdir(ds_dir):
            continue
        # List files that start with prefix and end with .csv
        candidates = [f for f in os.listdir(ds_dir)
                      if f.startswith(FILENAME_PREFIX) and f.lower().endswith(".csv")]
        # Apply exclusion by substring
        candidates = [f for f in candidates
                      if not any(excl in f for excl in FILENAME_EXCLUDE_SUBSTRINGS)]
        # Optional regex
        if FILENAME_REGEX is not None:
            rx = re.compile(FILENAME_REGEX)
            candidates = [f for f in candidates if rx.search(f)]

        if not candidates:
            # No matching file for this dataset, skip
            continue

        # Select the first (sorted) candidate
        candidates.sort()
        csv_path = os.path.join(ds_dir, candidates[0])
        pairs.append((ds, csv_path))

    return pairs


def load_rrmse_table(csv_path: str) -> pd.DataFrame:
    """Load a result CSV and return a tidy DataFrame:
    columns: ['dataset', 'model', 'prep', 'rrmse']
    """
    raw = pd.read_csv(csv_path)
    if MODEL_COL not in raw.columns:
        raise ValueError(f"{csv_path}: missing '{MODEL_COL}' column")

    # Melt wide table into tidy long format
    df = raw.melt(id_vars=[MODEL_COL], var_name="prep", value_name="rrmse")
    df = df.rename(columns={MODEL_COL: "model"})
    # Ensure numeric
    df["rrmse"] = pd.to_numeric(df["rrmse"], errors="coerce")
    # Drop rows with missing rrmse
    df = df.dropna(subset=["rrmse"])
    # Optionally restrict to certain preprocessings / models
    if RESTRICT_TO_PREPS is not None:
        if PREP_CASE_SENSITIVE:
            df = df[df["prep"].isin(RESTRICT_TO_PREPS)]
        else:
            lower_set = {p.lower() for p in RESTRICT_TO_PREPS}
            df = df[df["prep"].str.lower().isin(lower_set)]
    if RESTRICT_TO_MODELS is not None:
        df = df[df["model"].isin(RESTRICT_TO_MODELS)]
    return df


def benjamini_hochberg(pvals: List[float]) -> List[float]:
    """Benjamini-Hochberg FDR adjustment. Returns q-values in the original order.
    If pval is None (missing), returns None at the same position.
    """
    n = len(pvals)
    indexed = [(i, p) for i, p in enumerate(pvals)]
    # Filter out None
    valid = [(i, p) for i, p in indexed if p is not None]
    m = len(valid)
    if m == 0:
        return [None] * n
    # Sort by ascending p
    valid.sort(key=lambda t: t[1])
    ranks = {i: (rank+1) for rank, (i, _) in enumerate(valid)}
    qvals = [None] * n
    # Compute raw q = p * m / rank
    raw = [(i, min(1.0, p * m / ranks[i])) for (i, p) in valid]
    # Enforce monotonicity (non-increasing when traversing from high to low rank)
    # We process in reverse order of p (from largest rank to smallest)
    # and take cumulative minimum.
    # First, create a list in the same order as 'valid'
    qs_sorted = [min(1.0, p * m / (idx+1)) for idx, (_, p) in enumerate(valid)]
    # Now enforce monotone non-decreasing in rank (non-increasing when traversed reverse)
    for k in range(m - 2, -1, -1):
        qs_sorted[k] = min(qs_sorted[k], qs_sorted[k + 1])
    # Map back to original indices
    for (pos, (i, _)) in enumerate(valid):
        qvals[i] = qs_sorted[pos]
    return qvals


def exact_sign_test_pvalue(diffs: np.ndarray, delta: float) -> Tuple[Optional[float], int]:
    """Exact one-sided sign test for non-inferiority on Y = diffs - delta.
    H0: median(Y) >= 0  vs  H1: median(Y) < 0
    We remove ties where Y == 0.
    Returns (p_value, n_effective).
    """
    # Center by delta
    y = diffs - delta
    # Remove ties (zeros)
    mask = np.abs(y) > 0
    eff = y[mask]
    n_eff = eff.size
    if n_eff == 0:
        return None, 0

    # Count number of negatives
    s = np.sum(eff < 0)
    if SCIPY_AVAILABLE:
        # p = P[Binom(n, 0.5) <= s]
        from scipy.stats import binom
        p = binom.cdf(s, n_eff, 0.5)
    else:
        # Fallback exact computation (iterative sum) to avoid SciPy dependency
        from math import comb
        p = sum(comb(n_eff, k) * (0.5 ** n_eff) for k in range(0, int(s) + 1))
    return float(p), int(n_eff)


def wilcoxon_less_pvalue(diffs: np.ndarray, delta: float) -> Tuple[Optional[float], int]:
    """One-sided Wilcoxon signed-rank test on Y = diffs - delta with alternative='less'.
    Returns (p_value, n_effective) where n_effective excludes zeros as per Wilcoxon definition.
    """
    y = diffs - delta
    # SciPy wilcoxon handles zeros with zero_method='wilcox' by default in recent versions.
    # We explicitly set zero_method to 'wilcox' to drop zero-differences.
    if not SCIPY_AVAILABLE:
        return None, int(np.sum(np.abs(y) > 0))

    # If all are zeros or insufficient pairs, SciPy raises a warning / returns nan
    try:
        stat, p = wilcoxon(y, alternative='less', zero_method='wilcox', correction=False, mode='auto')
        # n_effective: count of non-zero pairs
        n_eff = int(np.sum(np.abs(y) > 0))
        if isinstance(p, float):
            return float(p), n_eff
        else:
            return None, n_eff
    except Exception:
        n_eff = int(np.sum(np.abs(y) > 0))
        return None, n_eff


def bootstrap_ci_median(diffs: np.ndarray, ci: float = 0.95, B: int = 2000, seed: int = 42) -> Tuple[float, float]:
    """Bootstrap percentile CI for the median of diffs.
    Returns (lower, upper).
    """
    rng = np.random.default_rng(seed)
    n = len(diffs)
    if n == 0:
        return np.nan, np.nan
    meds = []
    for _ in range(B):
        idx = rng.integers(0, n, n)
        sample = diffs[idx]
        meds.append(np.median(sample))
    lower = np.quantile(meds, (1 - ci) / 2.0)
    upper = np.quantile(meds, 1 - (1 - ci) / 2.0)
    return float(lower), float(upper)


