"""
Non-inferiority tests for model + preprocessing pairs using RRMSE tables.

Repository layout expected:
  /Results/asso_pp_model/<dataset_name>/*.csv

Each CSV must start with "results_" and must NOT contain any of the substrings in `FILENAME_EXCLUDE_SUBSTRINGS`.
The CSV structure is expected to be:
  - one row per model (column "Model")
  - one column per preprocessing (all other columns), values are RRMSE (float)

We compare Δ = RRMSE(candidate_model, prep, dataset) - RRMSE(reference, prep, dataset).
Two reference modes are available:
  1) fixed reference model (e.g., "Ridge_reg")
  2) per-dataset best model for the SAME preprocessing (lowest RRMSE in that dataset & prep)

For each (candidate_model, prep), we aggregate Δ across datasets (optionally across folds if present in your CSVs)
and compute three non-parametric procedures:
  a) Exact sign test (binomial) on Y = Δ - δ (H0: median(Y) >= 0 vs H1: < 0). We remove ties Y == 0.
  b) Wilcoxon signed-rank on Y = Δ - δ, one-sided (alternative='less'), ties handled as zeros.
  c) Bootstrap percentile CI for the median(Δ). Non-inferiority if UpperCI < δ.

Multiple testing is handled via Benjamini-Hochberg FDR separately for sign test and Wilcoxon.

Output: a CSV with one row per (candidate_model, preprocessing) combination, including
  counts, p-values, FDR-adjusted p-values, bootstrap CIs, and non-inferiority decisions.

Author: Generated by ChatGPT (comments in English).
"""

