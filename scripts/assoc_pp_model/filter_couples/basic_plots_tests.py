"""
Non-inferiority tests for model + preprocessing pairs using per-dataset CSVs.
This script:
  - Walks /Results/asso_pp_model/<dataset_name>/ for CSV files named "results_*.csv"
    that do NOT contain certain excluded substrings.
  - Automatically detects TASK TYPE per dataset CSV:
      * regression if any model name ends with "_reg"  (metric assumed to be RRMSE; smaller is better)
      * classification if any model ends with "_classif" (metric assumed to be Accuracy; larger is better)
    If both suffixes are present in a CSV, the dataset is skipped as ambiguous.
  - Builds Δ values per (candidate model, preprocessing, dataset):
      * regression: Δ = RRMSE(candidate) - RRMSE(reference)                (smaller is better)
      * classification: Δ = Accuracy(reference) - Accuracy(candidate)      (larger is better)
    => In BOTH tasks, Δ < δ supports non-inferiority of the candidate.
  - Applies THREE procedures MODEL-BY-MODEL (i.e., within each candidate model, across preprocessings):
      a) Exact sign test (binomial) on Y = Δ - δ (ties removed), one-sided "less"
      b) Wilcoxon signed-rank on Y = Δ - δ (one-sided "less"), ties handled as zero
      c) Bootstrap percentile CI for the median(Δ); non-inferiority if UpperCI < δ
  - Controls multiplicity with Benjamini-Hochberg (FDR) **within each (task, candidate model)**
    separately for sign test and Wilcoxon.
  - Outputs TWO CSV reports (one per task) and companion *_diffs.csv files.
  - Generates visualization figures per task: 4 subplots per figure (2x2),
    one subplot per candidate model, showing a "mini-forest" of median Δ with bootstrap CI
    across preprocessings for that model.

Author: Generated by ChatGPT. All code comments are in English.
"""

