def discover_dataset_csvs(root: str) -> List[Tuple[str, str]]:
    """Discover (dataset_name, csv_path) pairs under root.
    The FIRST CSV (sorted) in each dataset dir that matches the rules is selected.
    """
    pairs: List[Tuple[str, str]] = []
    if not os.path.isdir(root):
        print(f"[WARN] Root directory not found: {root}")
        return pairs

    for ds in sorted(os.listdir(root)):
        ds_dir = os.path.join(root, ds)
        if not os.path.isdir(ds_dir):
            continue
        candidates = [f for f in os.listdir(ds_dir)
                      if f.startswith(FILENAME_PREFIX) and f.lower().endswith(".csv")]
        candidates = [f for f in candidates
                      if not any(excl in f for excl in FILENAME_EXCLUDE_SUBSTRINGS)]
        if not candidates:
            continue
        candidates.sort()
        csv_path = os.path.join(ds_dir, candidates[0])
        pairs.append((ds, csv_path))
    return pairs


def detect_task_from_models(models: List[str]) -> str:
    """Detect task type from model names within a CSV.
    Returns "regression", "classification", or "ambiguous"/"unknown".
    - regression if any model endswith "_reg" and no model endswith "_classif"
    - classification if any endswith "_classif" and no endswith "_reg"
    - ambiguous if both are present
    - unknown if none matches
    """
    has_reg = any(isinstance(m, str) and m.endswith("_reg") for m in models)
    has_clf = any(isinstance(m, str) and m.endswith("_classif") for m in models)
    if has_reg and not has_clf:
        return "regression"
    if has_clf and not has_reg:
        return "classification"
    if has_reg and has_clf:
        return "ambiguous"
    return "unknown"


def benjamini_hochberg(pvals: List[Optional[float]]) -> List[Optional[float]]:
    """Benjamini–Hochberg FDR adjustment. None p-values are preserved as None."""
    n = len(pvals)
    with_idx = [(i, p) for i, p in enumerate(pvals) if p is not None]
    m = len(with_idx)
    if m == 0:
        return [None] * n
    # Sort by p ascending
    with_idx.sort(key=lambda t: t[1])
    # Compute q values with monotonicity
    qs = [None] * n
    prev_q = 1.0
    for rank, (i, p) in enumerate(reversed(with_idx), start=1):
        q = min(prev_q, p * m / (m - rank + 1))
        qs[i] = q
        prev_q = q
    return qs


def exact_sign_test_pvalue(diffs: np.ndarray, delta: float) -> Tuple[Optional[float], int]:
    """Exact one-sided sign test for non-inferiority on Y = diffs - delta.
    H0: median(Y) >= 0  vs  H1: median(Y) < 0
    Ties Y == 0 are removed.
    Returns (p_value, n_effective).
    """
    y = diffs - delta
    eff = y[np.abs(y) > 0]
    n_eff = eff.size
    if n_eff == 0:
        return None, 0
    s = int(np.sum(eff < 0))
    if SCIPY_AVAILABLE:
        p = float(binom.cdf(s, n_eff, 0.5))
    else:
        # Exact binomial CDF without SciPy
        from math import comb
        p = sum(comb(n_eff, k) * (0.5 ** n_eff) for k in range(0, s + 1))
    return p, n_eff


def wilcoxon_less_pvalue(diffs: np.ndarray, delta: float) -> Tuple[Optional[float], int]:
    """One-sided Wilcoxon signed-rank on Y = diffs - delta ('less').
    Returns (p_value, n_effective = count of non-zero pairs)."""
    y = diffs - delta
    n_eff = int(np.sum(np.abs(y) > 0))
    if n_eff == 0 or not SCIPY_AVAILABLE:
        return None, n_eff
    try:
        stat, p = wilcoxon(y, alternative="less", zero_method="wilcox", correction=False, mode="auto")
        return float(p), n_eff if isinstance(p, float) else (None, n_eff)
    except Exception:
        return None, n_eff


def bootstrap_ci_median(diffs: np.ndarray, ci: float, B: int, seed: int) -> Tuple[float, float]:
    """Bootstrap percentile CI for the median of diffs. Returns (lower, upper)."""
    rng = np.random.default_rng(seed)
    n = len(diffs)
    if n == 0:
        return (float("nan"), float("nan"))
    meds = np.empty(B, dtype=float)
    for b in range(B):
        idx = rng.integers(0, n, n)
        meds[b] = np.median(diffs[idx])
    alpha = 1 - ci
    lo = float(np.quantile(meds, alpha / 2))
    hi = float(np.quantile(meds, 1 - alpha / 2))
    return lo, hi


