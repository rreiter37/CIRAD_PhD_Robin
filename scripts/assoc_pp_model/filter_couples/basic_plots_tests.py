def harmonize_model_name(model: str) -> str:
    """Unify NICON and CNN into the same model family."""
    if not isinstance(model, str):
        return model
    if model.endswith("_reg"):
        if "NICON" in model or "CNN" in model:
            return "CNN_reg"
    if model.endswith("_classif"):
        if "NICON" in model or "CNN" in model:
            return "CNN_classif"
    return model

def collect_diffs_split_by_task(dataset_csvs: List[Tuple[str, str]],
                                reference_mode: str,
                                ref_model_reg: Optional[str],
                                ref_model_classif: Optional[str],
                                restrict_models: Optional[set],
                                restrict_preps: Optional[set],
                                prep_case_sensitive: bool) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Collect Δ across datasets and split into two tidy DataFrames (regression, classification).

    Returns:
      diffs_reg: columns [dataset, candidate_model, prep, delta_value]
      diffs_clf: columns [dataset, candidate_model, prep, delta_value]
    """
    reg_rows = []
    clf_rows = []

    for ds_name, csv_path in dataset_csvs:
        try:
            wide = pd.read_csv(csv_path)
        except Exception as e:
            print(f"[WARN] Failed to read CSV '{csv_path}': {e}")
            continue

        if MODEL_COL not in wide.columns:
            print(f"[WARN] Missing '{MODEL_COL}' in {csv_path}, skipping dataset.")
            continue

        models = [str(x) for x in wide[MODEL_COL].dropna().tolist()]
        task = detect_task_from_models(models)
        if task in ("ambiguous", "unknown"):
            print(f"[WARN] Dataset '{ds_name}' task is {task}; skipping.")
            continue

        # Long format
        df = wide.melt(id_vars=[MODEL_COL], var_name="prep", value_name="metric").rename(columns={MODEL_COL: "model"})
        df["model"] = df["model"].apply(harmonize_model_name)

        # Exclude unwanted preprocessings globally
        if EXCLUDE_PREPS:
            df = df[~df["prep"].isin(EXCLUDE_PREPS)]

        df["metric"] = pd.to_numeric(df["metric"], errors="coerce")
        df = df.dropna(subset=["metric"])


        # Restrictions
        if restrict_models is not None:
            df = df[df["model"].isin(restrict_models)]
        if restrict_preps is not None:
            if prep_case_sensitive:
                df = df[df["prep"].isin(restrict_preps)]
            else:
                df = df[df["prep"].str.lower().isin({p.lower() for p in restrict_preps})]

        if df.empty:
            continue

        pivot = df.pivot_table(index="model", columns="prep", values="metric", aggfunc="mean")

        if reference_mode == "fixed_model":
            ref_model = ref_model_reg if task == "regression" else ref_model_classif
            if ref_model not in pivot.index:
                # Can't compute diffs for this dataset
                continue
            ref_row = pivot.loc[ref_model]
            for cand in pivot.index:
                if cand == ref_model:
                    continue
                for prep in pivot.columns:
                    c_val = pivot.loc[cand, prep]
                    r_val = ref_row[prep]
                    if pd.isna(c_val) or pd.isna(r_val):
                        continue
                    if task == "regression":    # smaller is better
                        delta_val = float(c_val - r_val)
                        reg_rows.append((ds_name, cand, str(prep), delta_val))
                    else:                       # classification: larger is better
                        delta_val = float(r_val - c_val)
                        clf_rows.append((ds_name, cand, str(prep), delta_val))

        elif reference_mode == "per_dataset_best":
            for prep in pivot.columns:
                col = pivot[prep].dropna()
                if col.empty:
                    continue
                if task == "regression":   # best = min
                    best_model = col.idxmin()
                    best_val = float(col.min())
                else:                      # best = max
                    best_model = col.idxmax()
                    best_val = float(col.max())
                for cand in pivot.index:
                    if cand == best_model or pd.isna(pivot.loc[cand, prep]):
                        continue
                    if task == "regression":
                        delta_val = float(pivot.loc[cand, prep] - best_val)
                        reg_rows.append((ds_name, cand, str(prep), delta_val))
                    else:
                        delta_val = float(best_val - pivot.loc[cand, prep])
                        clf_rows.append((ds_name, cand, str(prep), delta_val))
        else:
            raise ValueError(f"Unknown reference_mode: {reference_mode}")

    diffs_reg = pd.DataFrame(reg_rows, columns=["dataset", "candidate_model", "prep", "delta_value"])
    diffs_clf = pd.DataFrame(clf_rows, columns=["dataset", "candidate_model", "prep", "delta_value"])
    return diffs_reg, diffs_clf


# ------------------------- Statistical tests (model-by-model) -------------------------

def run_tests_model_by_model(diffs_df: pd.DataFrame,
                             delta_margin: float,
                             alpha: float,
                             ci_level: float,
                             bootstrap_B: int,
                             seed: int,
                             apply_fdr: bool = False) -> pd.DataFrame:
    """Run sign test, Wilcoxon, and bootstrap CI **within each candidate model** across preprocessings.
    Grouping key is (candidate_model, prep). FDR is computed **within candidate model**.
    """
    if diffs_df.empty:
        return pd.DataFrame(columns=[
            "candidate_model","prep","n_datasets","n_pairs",
            "median_diff","mean_diff",
            "sign_p","sign_q","sign_n_eff","noninferior_sign","noninferior_sign_fdr",
            "wilcoxon_p","wilcoxon_q","wilcoxon_n_eff","noninferior_wilcoxon","noninferior_wilcoxon_fdr",
            "boot_ci_low","boot_ci_high","noninferior_bootstrap"
        ])

    rows = []
    grouped = diffs_df.groupby(["candidate_model", "prep"], sort=False)
    for (cand, prep), g in grouped:
        diffs = g["delta_value"].to_numpy(dtype=float)
        diffs = diffs[np.isfinite(diffs)]
        if diffs.size == 0:
            continue

        sign_p, sign_n = exact_sign_test_pvalue(diffs, delta_margin)
        wil_p, wil_n = wilcoxon_less_pvalue(diffs, delta_margin)
        ci_lo, ci_hi = bootstrap_ci_median(diffs, ci=ci_level, B=bootstrap_B, seed=seed)
        median_diff = float(np.median(diffs))
        mean_diff = float(np.mean(diffs))

        rows.append({
            "candidate_model": cand,
            "prep": prep,
            "n_datasets": int(g["dataset"].nunique()),
            "n_pairs": int(diffs.size),
            "median_diff": median_diff,
            "mean_diff": mean_diff,
            "sign_p": sign_p,
            "sign_n_eff": sign_n,
            "wilcoxon_p": wil_p,
            "wilcoxon_n_eff": wil_n,
            "boot_ci_low": ci_lo,
            "boot_ci_high": ci_hi,
        })

    out = pd.DataFrame(rows)

    # Compute FDR within each candidate model (over its preprocessings)
    if not out.empty:
        out = out.sort_values(["candidate_model", "prep"]).reset_index(drop=True)

        if apply_fdr:
            out["sign_q"] = np.nan
            out["wilcoxon_q"] = np.nan
            for cand, sub in out.groupby("candidate_model", sort=False):
                idx = sub.index
                out.loc[idx, "sign_q"] = benjamini_hochberg([out.loc[i, "sign_p"] for i in idx])
                out.loc[idx, "wilcoxon_q"] = benjamini_hochberg([out.loc[i, "wilcoxon_p"] for i in idx])

            out["noninferior_sign_fdr"] = out.apply(lambda r: (not pd.isna(r["sign_q"])) and (r["sign_q"] < alpha), axis=1)
            out["noninferior_wilcoxon_fdr"] = out.apply(lambda r: (not pd.isna(r["wilcoxon_q"])) and (r["wilcoxon_q"] < alpha), axis=1)
        else:
            out["sign_q"] = np.nan
            out["wilcoxon_q"] = np.nan
            out["noninferior_sign_fdr"] = np.nan
            out["noninferior_wilcoxon_fdr"] = np.nan

        out["noninferior_sign"] = out["sign_p"].apply(lambda p: (p is not None) and (p < alpha))
        out["noninferior_wilcoxon"] = out["wilcoxon_p"].apply(lambda p: (p is not None) and (p < alpha))
        out["noninferior_bootstrap"] = out["boot_ci_high"] < delta_margin

    return out



