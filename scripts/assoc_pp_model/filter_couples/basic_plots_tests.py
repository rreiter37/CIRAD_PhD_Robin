def make_visualizations_by_task_and_model(summary: pd.DataFrame, 
                                          delta_margin: float, 
                                          alpha: float, 
                                          output_dir: str, 
                                          task_label: str):
    """Generate volcano + forest plots per model, 
    and one global heatmap for all models within the task."""

    if summary.empty:
        print(f"[WARN] No summary to visualize for {task_label}.")
        return

    os.makedirs(output_dir, exist_ok=True)

    # ---------------- Per-model volcano + forest ----------------
    for cand_model, sub in summary.groupby("candidate_model"):
        sub = sub[~sub["prep"].isin(EXCLUDE_PREPS)]
        if sub.empty:
            continue

        model_safe = cand_model.replace("/", "_").replace(" ", "_")
        prefix = os.path.join(output_dir, f"{task_label}_{model_safe}")

        # Volcano
        plt.figure(figsize=(8,6))
        x = sub["median_diff"]
        y = -np.log10(sub["wilcoxon_p"].fillna(1.0))
        colors = []
        for md, p in zip(sub["median_diff"], sub["wilcoxon_p"]):
            if p is None or np.isnan(p):
                colors.append("gray")
            elif (p < alpha) and (md < delta_margin):
                colors.append("green")
            elif (p < alpha) and (md >= delta_margin):
                colors.append("red")
            else:
                colors.append("orange")
        plt.scatter(x, y, c=colors, alpha=0.7)
        plt.axvline(delta_margin, color="black", linestyle="--", label=f"delta={delta_margin}")
        plt.xlabel("Median Δ (candidate - reference)")
        plt.ylabel("-log10 p-value (Wilcoxon)")
        plt.title(f"Volcano plot - {cand_model} ({task_label})")
        plt.legend()
        plt.tight_layout()
        plt.savefig(f"{prefix}_volcano.png")
        plt.close()

        # Forest
        fig_height = max(6, 0.5*len(sub))
        fig, ax = plt.subplots(figsize=(10, fig_height))
        sorted_sub = sub.sort_values("median_diff")
        y_positions = range(len(sorted_sub))
        ax.errorbar(x=sorted_sub["median_diff"], y=y_positions,
                    xerr=[sorted_sub["median_diff"]-sorted_sub["boot_ci_low"],
                          sorted_sub["boot_ci_high"]-sorted_sub["median_diff"]],
                    fmt='o', ecolor="gray", capsize=3)
        ax.axvline(delta_margin, color="red", linestyle="--", label=f"delta={delta_margin}")
        ax.set_yticks(y_positions)
        labels = [f"{p}" for p in sorted_sub["prep"]]
        ax.set_yticklabels(labels, fontsize=9)
        ax.set_xlabel("Median Δ with bootstrap CI", fontsize=11)
        ax.set_title(f"Forest plot - {cand_model} ({task_label})", fontsize=12)
        ax.legend()
        plt.tight_layout()
        plt.savefig(f"{prefix}_forest.png")
        plt.close()

    # ---------------- Global heatmap for all models ----------------
    summary_no_pca = summary[~summary["prep"].isin(EXCLUDE_PREPS)]
    if summary_no_pca.empty:
        return

    decision_matrix = summary_no_pca.pivot(index="candidate_model", columns="prep",
                                           values="noninferior_wilcoxon")
    cmap = {True:1, False:0, None:np.nan}
    mat = decision_matrix.applymap(lambda v: cmap.get(v, np.nan))

    n_preps = len(mat.columns)
    n_models = len(mat.index)
    fig_width = max(12, 0.6*n_preps)
    fig_height = max(6, 0.5*n_models)

    plt.figure(figsize=(fig_width, fig_height))
    sns.heatmap(mat, cmap=sns.color_palette(["red","green"]),
                cbar=False, linewidths=0.5, linecolor="gray",
                annot=True, fmt="", xticklabels=True, yticklabels=True)

    plt.xticks(fontsize=8, rotation=45, ha="right")
    plt.yticks(fontsize=9, rotation=0)
    plt.title(f"Global Heatmap of non-inferiority (Wilcoxon) - {task_label}", fontsize=12)
    plt.xlabel("Preprocessing", fontsize=11)
    plt.ylabel("Model", fontsize=11)
    plt.tight_layout()
    plt.savefig(os.path.join(output_dir, f"{task_label}_heatmap_global.png"))
    plt.close()

    print(f"[INFO] Global heatmap saved for {task_label} in {output_dir}")


