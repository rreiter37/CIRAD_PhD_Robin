#!/usr/bin/env python3
"""
Plot summary figures for TabPFN classification results (accuracy only).

Expected input:
- {results_dir}/summary_metrics.csv
  generated by run_tabpfn_classif_on_all.py

Outputs:
- {results_dir}/figures_accuracy/
    - accuracy_bar_sorted.png
    - accuracy_box_by_type.png
    - accuracy_heatmap_type_x_dataset.png
    - accuracy_hist.png
    - accuracy_topk.csv

Notes:
- This script intentionally focuses on accuracy only, as requested.
- All comments are in English.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--results_dir",
        type=str,
        default="Results/tabpfn_classif_raw",
        help="Directory containing summary_metrics.csv produced by the TabPFN runner.",
    )
    parser.add_argument(
        "--out_dir",
        type=str,
        default=None,
        help="Directory to save figures. Default: {results_dir}/figures_accuracy",
    )
    parser.add_argument(
        "--top_k",
        type=int,
        default=30,
        help="Number of top datasets (by accuracy) to export and optionally highlight.",
    )
    parser.add_argument(
        "--max_bar_datasets",
        type=int,
        default=80,
        help="Max number of datasets to show in the sorted barplot (readability).",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=220,
        help="Figure DPI for saved PNG files.",
    )
    return parser.parse_args()


def _safe_out_dir(results_dir: Path, out_dir: Optional[str]) -> Path:
    if out_dir is None:
        return results_dir / "figures_accuracy"
    return Path(out_dir)


def load_summary_csv(results_dir: Path) -> pd.DataFrame:
    """
    Load summary_metrics.csv and validate required columns.
    """
    path = results_dir / "summary_metrics.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Missing summary file: {path}\n"
            "Run the TabPFN classification pipeline first to generate summary_metrics.csv."
        )

    df = pd.read_csv(path)

    required_cols = {"dataset_type", "dataset_name", "accuracy"}
    missing = required_cols - set(df.columns)
    if missing:
        raise ValueError(f"summary_metrics.csv is missing required columns: {sorted(list(missing))}")

    # Ensure accuracy is numeric and in [0, 1] if possible.
    df["accuracy"] = pd.to_numeric(df["accuracy"], errors="coerce")
    df = df.dropna(subset=["accuracy"]).copy()

    return df


def make_dataset_id(df: pd.DataFrame) -> pd.Series:
    """
    Build a compact dataset identifier used in plots.
    """
    return df["dataset_type"].astype(str) + " / " + df["dataset_name"].astype(str)


def save_topk_table(df: pd.DataFrame, out_dir: Path, top_k: int) -> None:
    """
    Save a small CSV with the top-K datasets by accuracy.
    """
    top = df.sort_values("accuracy", ascending=False).head(top_k).copy()
    top["dataset_id"] = make_dataset_id(top)
    cols = ["dataset_id", "dataset_type", "dataset_name", "accuracy", "n_train", "n_test", "n_features", "n_classes"]
    cols = [c for c in cols if c in top.columns]
    top[cols].to_csv(out_dir / "accuracy_topk.csv", index=False)


def plot_accuracy_bar_sorted(df: pd.DataFrame, out_dir: Path, max_bar_datasets: int, dpi: int) -> None:
    """
    Plot a sorted bar chart of accuracies across datasets.
    """
    df_sorted = df.sort_values("accuracy", ascending=False).copy()
    df_sorted["dataset_id"] = make_dataset_id(df_sorted)

    # Limit number of datasets for readability
    df_plot = df_sorted.head(max_bar_datasets).copy()

    plt.figure(figsize=(max(10, 0.16 * len(df_plot)), 6))
    plt.bar(np.arange(len(df_plot)), df_plot["accuracy"].to_numpy())
    plt.xticks(np.arange(len(df_plot)), df_plot["dataset_id"].tolist(), rotation=90, fontsize=8)
    plt.ylabel("Accuracy")
    plt.title(f"TabPFN classification accuracy (top {len(df_plot)} datasets, sorted)")
    plt.ylim(0.0, 1.0)
    plt.tight_layout()
    plt.savefig(out_dir / "accuracy_bar_sorted.png", dpi=dpi)
    plt.close()


def plot_accuracy_box_by_type(df: pd.DataFrame, out_dir: Path, dpi: int) -> None:
    """
    Plot a boxplot of accuracy grouped by dataset_type.
    """
    # Group accuracies by type
    grouped = []
    labels = []
    for t in sorted(df["dataset_type"].unique().tolist()):
        vals = df.loc[df["dataset_type"] == t, "accuracy"].dropna().to_numpy()
        if len(vals) > 0:
            grouped.append(vals)
            labels.append(str(t))

    plt.figure(figsize=(max(10, 0.6 * len(labels)), 6))
    plt.boxplot(grouped, tick_labels=labels, showfliers=True)
    plt.xticks(rotation=45, ha="right")
    plt.ylabel("Accuracy")
    plt.title("Accuracy distribution by dataset_type")
    plt.ylim(0.0, 1.0)
    plt.tight_layout()
    plt.savefig(out_dir / "accuracy_box_by_type.png", dpi=dpi)
    plt.close()


def plot_accuracy_heatmap_type_x_dataset(df: pd.DataFrame, out_dir: Path, dpi: int) -> None:
    """
    Plot a heatmap of accuracy with:
      - rows: dataset_type
      - cols: dataset_name
    This is useful when each type contains multiple analytes/datasets.
    """
    pivot = df.pivot_table(
        index="dataset_type",
        columns="dataset_name",
        values="accuracy",
        aggfunc="max",  # if duplicates exist, keep the best one
    )

    # If there are too many columns, the heatmap may be huge; we still save it.
    data = pivot.to_numpy()
    if data.size == 0:
        return

    plt.figure(figsize=(max(10, 0.25 * pivot.shape[1]), max(5, 0.5 * pivot.shape[0])))
    im = plt.imshow(data, aspect="auto", vmin=0.0, vmax=1.0)
    plt.colorbar(im, label="Accuracy")
    plt.yticks(np.arange(pivot.shape[0]), pivot.index.astype(str).tolist())
    plt.xticks(np.arange(pivot.shape[1]), pivot.columns.astype(str).tolist(), rotation=90, fontsize=7)
    plt.title("Accuracy heatmap (dataset_type × dataset_name)")
    plt.tight_layout()
    plt.savefig(out_dir / "accuracy_heatmap_type_x_dataset.png", dpi=dpi)
    plt.close()


def plot_accuracy_hist(df: pd.DataFrame, out_dir: Path, dpi: int) -> None:
    """
    Plot a histogram of accuracies across all datasets.
    """
    vals = df["accuracy"].dropna().to_numpy()
    plt.figure(figsize=(8, 5))
    plt.hist(vals, bins=20)
    plt.xlabel("Accuracy")
    plt.ylabel("Count")
    plt.title("Accuracy distribution across datasets")
    plt.xlim(0.0, 1.0)
    plt.tight_layout()
    plt.savefig(out_dir / "accuracy_hist.png", dpi=dpi)
    plt.close()


def main() -> None:
    args = parse_args()

    results_dir = Path(args.results_dir)
    out_dir = _safe_out_dir(results_dir, args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    df = load_summary_csv(results_dir)

    # Save a handy "top-K" table
    save_topk_table(df, out_dir, top_k=args.top_k)

    # Generate figures (accuracy only)
    plot_accuracy_bar_sorted(df, out_dir, max_bar_datasets=args.max_bar_datasets, dpi=args.dpi)
    plot_accuracy_box_by_type(df, out_dir, dpi=args.dpi)
    plot_accuracy_heatmap_type_x_dataset(df, out_dir, dpi=args.dpi)
    plot_accuracy_hist(df, out_dir, dpi=args.dpi)

    print("✅ Figures saved to:", out_dir)


if __name__ == "__main__":
    main()
